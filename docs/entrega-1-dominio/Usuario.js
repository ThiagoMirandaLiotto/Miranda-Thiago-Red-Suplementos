class Usuario {
    constructor(idUsuario, nombre, apellido, email, contrasena, telefono, fechaAlta, activo) {
        this.idUsuario = idUsuario;
        this.nombre = nombre;
        this.apellido = apellido;
        this.email = email;
        this.contrasena = contrasena;
        this.telefono = telefono;
        this.fechaAlta = fechaAlta;
        this.activo = activo;
    }
}

export default Usuario;
